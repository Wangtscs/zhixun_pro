import { chromium } from '../NEPHH/NEPHH-Admin/node_modules/@playwright/test/index.mjs'
import assert from 'node:assert/strict'
import { fileURLToPath } from 'node:url'
import { mkdir } from 'node:fs/promises'
process.chdir(fileURLToPath(new URL('..', import.meta.url)))
const browser = await chromium.launch({channel:'msedge',headless:false})
const page = await browser.newPage({viewport:{width:1440,height:1000}})
const errors=[],requests=[]
page.on('pageerror',e=>errors.push(e.message))
page.on('request',r=>{if(/^https?:/.test(r.url()))requests.push(r.url())})
try {
 await page.goto(new URL('./workbench.html', import.meta.url).href)
 await page.locator('#summary [data-queue="draft"]').click()
 const task=page.locator('#task-list [data-task]').first()
 const id=await task.getAttribute('data-task')
 await task.click()
 await page.locator('#demo-worker').selectOption({label:'林巡检'})
 await page.locator('#demo-action').click()
 await page.locator('#role').selectOption('inspector')
 await page.locator('#summary [data-queue="assigned"]').click()
 await page.locator(`#task-list [data-task="${id}"]`).click()
 assert.equal(await page.locator('#demo-action').getAttribute('data-action'),'接单')
 await page.locator('#demo-action').click()
 await page.locator(`#task-list [data-task="${id}"]`).click()
 assert.equal(await page.locator('#demo-action').getAttribute('data-action'),'开始处理')
 await page.locator('#demo-action').click()
 await page.locator(`#task-list [data-task="${id}"]`).click()
 await page.locator('#demo-action').click()
 assert.equal(await page.locator('#overlay').isVisible(),true,'Empty result must not submit')
 await page.locator('#demo-result').fill('虚构原型试走：完成检查')
 await page.locator('#demo-action').click()
 await page.locator('#role').selectOption('manager')
 await page.locator('#summary [data-queue="review"]').click()
 await page.locator(`#task-list [data-task="${id}"]`).click()
 assert.equal(await page.locator('#demo-action').getAttribute('data-action'),'通过复核')
 await page.locator('#demo-action').click()
 await page.locator('#role').selectOption('readonly')
 await page.locator('#task-list [data-task]').first().click()
 assert.equal(await page.locator('#demo-action').count(),0)
 await page.keyboard.press('Escape')
 assert.equal(await page.locator('#overlay').isVisible(),false)
 assert.equal(await page.evaluate(()=>document.activeElement?.hasAttribute('data-task')),true,'Closing details restores task focus')
 await page.locator('#open-space').click()
 await page.locator('#space-view').waitFor({state:'visible'})
 await page.locator('#theme').click()
 assert.equal(await page.locator('html').getAttribute('data-theme'),'light')
 await page.locator('#toast').waitFor({state:'hidden'})
 await mkdir('NEPHH/docs/verification/prototype-assets',{recursive:true})
 await page.screenshot({path:'NEPHH/docs/verification/prototype-assets/space-light.png',fullPage:true})
 await page.setViewportSize({width:390,height:844})
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth),'Narrow layout must not overflow the document')
 await page.screenshot({path:'NEPHH/docs/verification/prototype-assets/narrow.png',fullPage:true})
 assert.deepEqual(errors,[])
 assert.deepEqual(requests,[])
 console.log(JSON.stringify({passed:true,roleFlow:true,emptyResultRejected:true,readonly:true,escape:true,space:true,theme:true,pageErrors:0,networkRequests:0}))
} finally {await browser.close()}
