import { chromium } from '@playwright/test'
const browser=await chromium.launch({channel:'msedge',headless:true})
const page=await browser.newPage({viewport:{width:1440,height:900}})
const errors=[];page.on('pageerror',e=>errors.push(e.message))
await page.goto('http://127.0.0.1:5173')
await page.getByRole('button',{name:'一键进入演示环境'}).click()
await page.getByRole('heading',{name:'总览',exact:true}).waitFor()
await page.screenshot({path:'preview-overview.png',fullPage:true})
await page.getByRole('button',{name:'节点管理',exact:true}).click()
await page.getByPlaceholder('搜索节点编号或位置').fill('TN-A01')
if(await page.locator('tbody tr').count()!==1)throw Error('节点搜索失败')
await page.getByRole('button',{name:'查看 ›',exact:true}).click()
await page.getByRole('heading',{name:'TN-A01',exact:true}).waitFor()
await page.getByRole('button',{name:'关闭详情'}).click()
await page.getByRole('button',{name:'工单管理',exact:true}).click()
await page.getByRole('button',{name:'派单',exact:true}).first().click()
await page.getByRole('button',{name:'确认派单',exact:true}).click()
await page.getByRole('status').filter({hasText:'工单已成功派发'}).waitFor()
await page.getByRole('button',{name:'审计日志',exact:true}).click()
if(!await page.locator('tbody').innerText().then(t=>t.includes('派发工单')))throw Error('审计记录失败')
await page.getByRole('button',{name:'个人设置',exact:true}).click()
await page.getByRole('button',{name:'保存修改'}).click()
await page.getByRole('status').filter({hasText:'个人资料已保存'}).waitFor()
await page.setViewportSize({width:390,height:844});await page.screenshot({path:'preview-mobile.png',fullPage:true})
console.log(JSON.stringify({checks:'登录、总览、搜索、节点详情、派单、审计、资料保存',errors}))
await browser.close();if(errors.length)process.exit(1)
